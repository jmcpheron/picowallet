_cache = {}
_pal = framebuf.FrameBuffer(bytearray(4), 2, 1, framebuf.RGB565)


def _build(name, scale):
    rows = ART[name]
    w = 16 * scale
    fb = framebuf.FrameBuffer(bytearray(w * w // 8), w, w, framebuf.MONO_HLSB)
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch == "#":
                if scale == 1:
                    fb.pixel(x, y, 1)
                else:
                    fb.fill_rect(x * scale, y * scale, scale, scale, 1)
    return fb


def draw(d, name, x, y, color, scale=1):
    """Blit the icon in `color`; untouched pixels stay as they were."""
    fb = _cache.get((name, scale))
    if fb is None:
        fb = _cache[(name, scale)] = _build(name, scale)
    _pal.pixel(1, 0, color)
    d.blit(fb, x, y, 0, _pal)


def names():
    return sorted(ART)
